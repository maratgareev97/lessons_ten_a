# В файле содержится последовательность целых чисел. Элементы последовательности могут
# принимать целые значения от -100 000 до 100 000 включительно. Определите количество троек
# элементов последовательности, в которых все числа состоят из разного количества разрядов,
# а сумма элементов тройки не меньше максимального элемента последовательности, который является
# четырёхзначным числом и оканчивается на 22. В ответе запишите количество найденных троек чисел,
# затем максимальную из сумм элементов таких троек. В данной задаче под тройкой подразумевается
# три идущих подряд элемента последовательности.

file = list(map(int, open("17_14258.txt").readlines()))

mass = []
for i in file:
    if len(str(abs(i))) == 4 and str(abs(i))[-2:] == "22":
        mass.append(i)
max_4_22 = max(mass)

max_sum = -1000000000

count = 0
for i in range(len(file)-2):
    k=0
    if (len(str(abs(file[i]))) != len(str(abs(file[i+1])))):
        k+=1
    if (len(str(abs(file[i]))) != len(str(abs(file[i+2])))):
        k += 1
    if (len(str(abs(file[i+1]))) != len(str(abs(file[i + 2])))):
        k += 1

    if k==3:
        if (file[i]+file[i+1]+file[i+2])>=max_4_22:
            count+=1
            if (file[i]+file[i+1]+file[i+2])>=max_sum:
                max_sum = file[i]+file[i+1]+file[i+2]

print(count, max_sum)


