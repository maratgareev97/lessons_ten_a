# Определите количество троек элементов последовательности, в которых ровно два элемента имеют
# остаток при делении на 40 равный 15, и не более двух элементов являются кратными 7.
# В ответе запишите количество найденных троек, затем сумму элементов данных троек, у которых
# остаток при делении на 40 не равен 15.

file = list(map(int, open("17_23903.txt").readlines()))

max_sum = 0

count = 0
for i in range(len(file)-2):
    k1=0
    if file[i]%40==15:
        k1+=1
    if file[i+1]%40==15:
        k1 += 1
    if file[i+2]%40==15:
        k1 += 1
    k2 = 0
    if file[i] % 7== 0:
        k2 += 1
    if file[i + 1] % 7 == 0:
        k2 += 1
    if file[i + 2] % 7 == 0:
        k2 += 1

    if k1==2 and k2<=2:
        count+=1

    k3=0
    if file[i] % 40 != 15:
        k3 += file[i]
    if file[i + 1] % 40 != 15:
        k3 += file[i+1]
    if file[i + 2] % 40 != 15:
        k3 += file[i+2]
    max_sum += k3

print(count, max_sum)


