# Сколько неудовлетворительных оценок было получено учениками? Если хотя бы один из учеников
# правильно решил все задачи, выведите YES, иначе выведите NO. Программа получает на вход
# количество учеников в классе N (1 ≤ N ≤ 30), затем для каждого ученика вводится количество
# правильно решённых примеров.

